/// Scales a phase increment by `2^(cents/1200)`: the octaves are shifts, the
/// rest goes through [`SEMITONE_Q30`] and [`CENT_Q30`]. Exact to well below a
/// cent for every increment the synth uses.
pub fn scale_by_cents(inc: u64, cents: i32) -> u64 {
    let octaves = cents.div_euclid(1200);
    let rest = cents.rem_euclid(1200) as usize;
    let ratio = (SEMITONE_Q30[rest / 100] as u64 * CENT_Q30[rest % 100] as u64) >> 30;
    let scaled = ((inc as u128 * ratio as u128) >> 30) as u64;
    if octaves >= 0 {
        scaled << octaves.min(16)
    } else {
        scaled >> (-octaves).min(63)
    }
}

/// Sine of a 32-bit phase (a full turn = 2^32), Q15, linearly interpolated
/// between the table steps.
pub fn sine(phase: u32) -> i32 {
    let i = (phase >> 24) as usize;
    let frac = ((phase >> 8) & 0xFFFF) as i32;
    let a = SINE[i] as i32;
    let b = SINE[(i + 1) & 255] as i32;
    a + (((b - a) * frac) >> 16)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_match_the_float_formulas() {
        for (i, &v) in SINE.iter().enumerate() {
            let want = (32767.0 * (2.0 * std::f64::consts::PI * i as f64 / 256.0).sin()).round();
            assert_eq!(v as f64, want, "SINE[{i}]");
        }
        for (i, &v) in SEMITONE_Q30.iter().enumerate() {
            let want = (2f64.powf(i as f64 / 12.0) * (1u64 << 30) as f64).round();
            assert_eq!(v as f64, want, "SEMITONE_Q30[{i}]");
        }
        for (c, &v) in CENT_Q30.iter().enumerate() {
            let want = (2f64.powf(c as f64 / 1200.0) * (1u64 << 30) as f64).round();
            assert_eq!(v as f64, want, "CENT_Q30[{c}]");
        }
    }

    #[test]
    fn scaling_by_cents_is_accurate() {
        let inc: u64 = 1 << 28;
        for cents in (-4800..=4800).step_by(37) {
            let got = scale_by_cents(inc, cents) as f64;
            let want = inc as f64 * 2f64.powf(cents as f64 / 1200.0);
            let err_cents = 1200.0 * (got / want).log2();
            assert!(err_cents.abs() < 0.01, "{cents} cents: {err_cents}");
        }
        assert_eq!(scale_by_cents(1000, 1200), 2000);
        assert_eq!(scale_by_cents(1000, -1200), 500);
    }

    #[test]
    fn interpolated_sine_hits_the_table_and_stays_in_range() {
        assert_eq!(sine(0), 0);
        assert_eq!(sine(1 << 30), 32767);
        assert_eq!(sine(3 << 30), -32767);
        for k in 0..4096u32 {
            assert!(sine(k << 20).abs() <= 32767);
        }
    }
}
