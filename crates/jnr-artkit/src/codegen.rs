//! Emits Rust source that rebuilds an [`Atlas`]'s metadata at runtime.
//! Used by `jnr-assets/build.rs`; the pixels are embedded separately with
//! `include_bytes!` and passed in.

use std::fmt::Write;

use crate::atlas::{Atlas, Rect};

/// Rust source defining `fn generated_atlas(pixels: &'static [u8]) -> Atlas`.
/// Paths are fully qualified via `::jnr_artkit::atlas`.
pub fn atlas_rust_source(atlas: &Atlas) -> String {
    let mut s = String::new();
    s.push_str("// @generated by jnr-assets/build.rs from art/. Do not edit.\n");
    s.push_str("#[allow(clippy::all)]\n");
    s.push_str("fn generated_atlas(pixels: &'static [u8]) -> ::jnr_artkit::atlas::Atlas {\n");
    s.push_str("    use ::jnr_artkit::atlas::{Atlas, AtlasAnim, AtlasSprite, Point, Rect};\n");
    s.push_str("    #[allow(unused)]\n");
    s.push_str("    fn r(x: u32, y: u32, w: u32, h: u32) -> Rect { Rect { x, y, w, h } }\n");
    let _ = writeln!(
        s,
        "    Atlas {{\n        width: {},\n        height: {},\n        pixels: ::std::borrow::Cow::Borrowed(pixels),\n        sprites: vec![",
        atlas.width, atlas.height
    );
    for sp in &atlas.sprites {
        let _ = writeln!(
            s,
            "            AtlasSprite {{\n                name: {:?}.into(),\n                width: {},\n                height: {},\n                origin: Point {{ x: {}, y: {} }},\n                hitbox: {},\n                mirrored: {},\n                anims: vec![",
            sp.name,
            sp.width,
            sp.height,
            sp.origin.x,
            sp.origin.y,
            rect(sp.hitbox),
            sp.mirrored
        );
        for a in &sp.anims {
            let _ = writeln!(
                s,
                "                    AtlasAnim {{ name: {:?}.into(), ticks: {}, looping: {}, frames: vec![{}], mirrored_frames: vec![{}] }},",
                a.name,
                a.ticks,
                a.looping,
                rects(&a.frames),
                rects(&a.mirrored_frames)
            );
        }
        s.push_str("                ],\n            },\n");
    }
    s.push_str("        ],\n    }\n}\n");
    s
}

fn rect(r: Rect) -> String {
    format!("r({}, {}, {}, {})", r.x, r.y, r.w, r.h)
}

fn rects(rs: &[Rect]) -> String {
    rs.iter().map(|&r| rect(r)).collect::<Vec<_>>().join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::atlas::{AtlasAnim, AtlasSprite, Point};

    #[test]
    fn emits_all_fields() {
        let atlas = Atlas {
            width: 64,
            height: 8,
            pixels: Vec::new().into(),
            sprites: vec![AtlasSprite {
                name: "box".into(),
                width: 2,
                height: 3,
                origin: Point { x: 1, y: 3 },
                hitbox: Rect {
                    x: 0,
                    y: 0,
                    w: 2,
                    h: 3,
                },
                mirrored: true,
                anims: vec![AtlasAnim {
                    name: "idle".into(),
                    ticks: 30,
                    looping: true,
                    frames: vec![Rect {
                        x: 1,
                        y: 1,
                        w: 2,
                        h: 3,
                    }],
                    mirrored_frames: vec![Rect {
                        x: 4,
                        y: 1,
                        w: 2,
                        h: 3,
                    }],
                }],
            }],
        };
        let src = atlas_rust_source(&atlas);
        assert!(src.contains("width: 64,"));
        assert!(src.contains("name: \"box\".into()"));
        assert!(src.contains("origin: Point { x: 1, y: 3 }"));
        assert!(src.contains("mirrored: true"));
        assert!(src.contains("frames: vec![r(1, 1, 2, 3)], mirrored_frames: vec![r(4, 1, 2, 3)]"));
        assert_eq!(src, atlas_rust_source(&atlas), "deterministic");
    }
}
